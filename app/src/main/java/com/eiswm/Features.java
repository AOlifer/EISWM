package com.eiswm;

/** Функции, которые есть в коде, но пока выключены. */
final class Features {
    /**
     * Прощание при выключении зажигания: звук, картинка и сводка с итогами поездки.
     * Выключено: экран и усилитель машины гаснут сразу при выключении зажигания, и прощание не
     * успевает. При false нет вкладок «Прощание» в разделах, прощание не срабатывает и поездка
     * не считается; код, строки и ресурсы остаются.
     */
    static final boolean FAREWELL = false;

    /**
     * Сводка с итогами поездки (вкладка «Итоги» в разделе «Сводка»). Показывается в конце поездки
     * по событию, выбранному на вкладке (по умолчанию — переключение в P), а не при выключении
     * зажигания: экран и усилитель гаснут сразу. Включена отдельно от звуков и картинок прощания.
     */
    static final boolean FAREWELL_SUMMARY = true;

    /**
     * Озвучка сводки. Выключено: в машине нет синтезатора речи, а сторонние (sherpa-onnx) работают
     * медленно, и приложение не смогло через них заговорить. При false нет выключателя
     * «Озвучивать сводку», кнопок ▶ и подсказки про синтезатор, сводка не озвучивается; код
     * и строки остаются.
     */
    static final boolean SPEECH = false;

    /** Температура в салоне: машина отдаёт всегда 0 (проверено и с включённым климатом), пункт скрыт. */
    static final boolean CABIN_TEMP = false;

    /**
     * Другие события для «Итогов», кроме переключения в P (ремень, дверь, стояночный тормоз):
     * в машине не сработали, спрятаны до выяснения. При false выбора «Когда показывать» нет.
     */
    static final boolean FINISH_EXTRA = false;

    /** Нужно ли считать поездку: для прощания или для сводки с итогами. */
    static boolean trip() {
        return FAREWELL || FAREWELL_SUMMARY;
    }

    private Features() {
    }
}
